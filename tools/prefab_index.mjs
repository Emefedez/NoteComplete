// Writes apps/reader/prefabs/index.js from the shipped modules' module.json files: their
// manifests and their code (render.js), imported statically so prefabs draw at once, in the
// reader and in Node (MCP). Run by tools/build_web.py; prefab-registry.test.mjs checks the
// file is up to date. Folders starting with "_" (the template) and "kit" are not modules.
//   node tools/prefab_index.mjs [--check]
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const dir = fileURLToPath(new URL('../apps/reader/prefabs/', import.meta.url));
export function prefabIndex(root = dir) {
  const modules = readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith('_') && d.name !== 'kit' && existsSync(path.join(root, d.name, 'module.json')))
    .map((d) => ({ folder: d.name, manifest: JSON.parse(readFileSync(path.join(root, d.name, 'module.json'), 'utf8')), code: existsSync(path.join(root, d.name, 'render.js')) }))
    .sort((a, b) => (a.manifest.order ?? 1000) - (b.manifest.order ?? 1000) || a.manifest.id.localeCompare(b.manifest.id));
  const name = (m) => `m_${m.folder.replace(/\W/g, '_')}`;
  return [
    '// Generated by tools/prefab_index.mjs from the module.json files: do not edit.',
    ...modules.filter((m) => m.code).map((m) => `import * as ${name(m)} from './${m.folder}/render.js';`),
    '',
    'export const MODULES = [',
    ...modules.map((m) => `  { folder: ${JSON.stringify(m.folder)}, manifest: ${JSON.stringify(m.manifest)}, code: ${m.code ? name(m) : '{}'} },`),
    '];',
    '',
  ].join('\n');
}
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const text = prefabIndex();
  const target = path.join(dir, 'index.js');
  if (process.argv.includes('--check')) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== text) { console.error('apps/reader/prefabs/index.js is out of date: run node tools/prefab_index.mjs'); process.exit(1); }
  } else writeFileSync(target, text);
}
