// Writes apps/reader/prefabs/index.js from the shipped modules' module.json files and
// prefabs/packs.json (docs/TABLES-AND-OFFICE.md, phase 7): every manifest, so the picker can
// list packs that are not installed; the code (render.js) of the core pack imported statically,
// so the essentials draw at once; and for every other module a `load()` that imports its code
// when its pack is installed (prefab-registry.js). A module that lists its cards in code
// ("prefabs": "code") also gets those cards' names here (no specs), so the picker can show
// them before the pack is downloaded. Run by tools/build_web.py; prefab-registry.test.mjs
// checks the file is up to date. Folders starting with "_" (the template) and "kit" are not
// modules.
//   node tools/prefab_index.mjs [--check]
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const dir = fileURLToPath(new URL('../apps/reader/prefabs/', import.meta.url));

// The shipped modules, in their order: { folder, manifest, code (has render.js) }.
export function shippedModules(root = dir) {
  return readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith('_') && d.name !== 'kit' && existsSync(path.join(root, d.name, 'module.json')))
    .map((d) => ({ folder: d.name, manifest: JSON.parse(readFileSync(path.join(root, d.name, 'module.json'), 'utf8')), code: existsSync(path.join(root, d.name, 'render.js')) }))
    .sort((a, b) => (a.manifest.order ?? 1000) - (b.manifest.order ?? 1000) || a.manifest.id.localeCompare(b.manifest.id));
}
export const readPacks = (root = dir) => (existsSync(path.join(root, 'packs.json')) ? JSON.parse(readFileSync(path.join(root, 'packs.json'), 'utf8')) : {});
// A module's pack: the one its manifest names, else a pack of its own.
export const packIdOf = (manifest) => String(manifest.pack || manifest.id);

export async function prefabIndex(root = dir) {
  const modules = shippedModules(root);
  const packs = readPacks(root);
  const core = (m) => !!packs[packIdOf(m.manifest)]?.core;
  const name = (m) => `m_${m.folder.replace(/\W/g, '_')}`;
  const entry = async (m) => {
    const head = `folder: ${JSON.stringify(m.folder)}, manifest: ${JSON.stringify(m.manifest)}`;
    if (!m.code) return `{ ${head}, code: {} }`;
    if (core(m)) return `{ ${head}, code: ${name(m)} }`;
    let cards = '';
    if (m.manifest.prefabs === 'code') {
      const code = await import(pathToFileURL(path.join(root, m.folder, 'render.js')).href);
      const list = (code.prefabs?.() || []).map(({ id, group, label, hint, icon }) => ({ id, group, label, hint, icon }));
      cards = `, cards: ${JSON.stringify(list)}`;
    }
    return `{ ${head}, load: () => import('./${m.folder}/render.js')${cards} }`;
  };
  return [
    '// Generated by tools/prefab_index.mjs from the module.json files and packs.json: do not edit.',
    ...modules.filter((m) => m.code && core(m)).map((m) => `import * as ${name(m)} from './${m.folder}/render.js';`),
    '',
    `export const PACKS = ${JSON.stringify(packs)};`,
    '',
    'export const MODULES = [',
    ...(await Promise.all(modules.map(async (m) => `  ${await entry(m)},`))),
    '];',
    '',
  ].join('\n');
}
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const text = await prefabIndex();
  const target = path.join(dir, 'index.js');
  if (process.argv.includes('--check')) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== text) { console.error('apps/reader/prefabs/index.js is out of date: run node tools/prefab_index.mjs'); process.exit(1); }
  } else writeFileSync(target, text);
}
